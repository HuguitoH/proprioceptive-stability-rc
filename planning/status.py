"""Progress snapshot for replanning: what is done, when it finished and what is left.

Each fact comes from one place. GitHub says what is done (closed issues and
closed milestones). log/hours.csv says when a task was last worked on, which is
when it finished. log/remaining.csv holds the estimate of the hours left on each
started task, appended at every review and never edited.

The snapshot is written to planning/status.yaml and committed. The planner only
reads that file, so it never touches the network, the tests run offline, and a
revised plan can be rebuilt exactly as it was on its status date.
"""
from __future__ import annotations

import csv
import json
import re
import subprocess
from datetime import date
from pathlib import Path

from .calendar import week_of
from .model import Config

TASK_ID = re.compile(r"^(M\d+|\d+\.\d+)\b")


def task_id(title: str) -> str | None:
    """Plan id at the start of an issue or milestone title, such as '2.1' or 'M0'."""
    match = TASK_ID.match(title.strip())
    return match.group(1) if match else None


def last_worked(rows: list[dict[str, str]]) -> dict[str, date]:
    """Latest date with hours logged against each task (rows of log/hours.csv)."""
    latest: dict[str, date] = {}
    for row in rows:
        day = date.fromisoformat(row["date"])
        task = row["task_id"]
        if task not in latest or day > latest[task]:
            latest[task] = day
    return latest


def latest_remaining(rows: list[dict[str, str]]) -> dict[str, float]:
    """Most recent estimate of the hours left on each task (rows of log/remaining.csv)."""
    latest: dict[str, tuple[date, float]] = {}
    for row in rows:
        day = date.fromisoformat(row["date"])
        task = row["task_id"]
        if task not in latest or day >= latest[task][0]:
            latest[task] = (day, float(row["remaining_hours"]))
    return {task: hours for task, (_, hours) in latest.items()}


def snapshot(config: Config, as_of: date, closed: dict[str, date], worked: dict[str, date],
             remaining: dict[str, float], known: set[str]) -> dict:
    """Combine the three sources into the status of the network tasks.

    A finished task is placed in the week it was last worked on. One with no
    hours logged (a milestone, say) falls back to the day it was closed. Tasks
    outside the network, such as the ongoing 1.1 and 1.2, are left out.
    """
    done = {t: week_of(config, worked.get(t, closed_on)) for t, closed_on in closed.items() if t in known}
    left = {t: h for t, h in remaining.items() if t in known and t not in done}
    return {"as_of": as_of, "done": dict(sorted(done.items())), "remaining": dict(sorted(left.items()))}


def render(status: dict) -> str:
    lines = ["# Generated by `python -m planning status`. Do not edit by hand:",
             "# close issues on GitHub and log estimates in log/remaining.csv instead.",
             f"as_of: {status['as_of'].isoformat()}",
             "done:                 # task: 1-based week it finished"]
    lines += [f'  "{t}": {w}' for t, w in status["done"].items()] or ["  {}"]
    lines.append("remaining:            # task: hours left")
    lines += [f'  "{t}": {h:g}' for t, h in status["remaining"].items()] or ["  {}"]
    return "\n".join(lines) + "\n"


def read_csv(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def fetch_closed(repository: str) -> dict[str, date]:
    """Closed issues and milestones on GitHub, by plan id, with the day they closed.

    Needs the gh CLI, logged in. This is the only part that uses the network.
    """
    repo = repository.removeprefix("https://github.com/").strip("/")
    issues = json.loads(_gh("issue", "list", "--repo", repo, "--state", "closed",
                            "--limit", "500", "--json", "title,closedAt"))
    milestones = json.loads(_gh("api", f"repos/{repo}/milestones?state=closed&per_page=100"))
    closed: dict[str, date] = {}
    for title, when in ([(i["title"], i["closedAt"]) for i in issues]
                        + [(m["title"], m["closed_at"]) for m in milestones]):
        tid = task_id(title)
        if tid and when:
            closed[tid] = date.fromisoformat(when[:10])
    return closed


def _gh(*args: str) -> str:
    return subprocess.run(["gh", *args], check=True, capture_output=True, text=True).stdout
